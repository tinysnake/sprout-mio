#!/usr/bin/env node
// The shadcn CLI writes theme tokens into the framework's global stylesheet, which it
// guesses wrong for TanStack Start (it targets app/globals.css). This applies the same
// preset tokens to src/theme.css so the step is repeatable instead of hand-copied.
import { writeFileSync } from 'node:fs'

const PRESET_URL =
  process.env.SHADCN_PRESET_URL ??
  'https://ui.shadcn.com/init?base=base&style=nova&baseColor=neutral&theme=neutral&iconLibrary=lucide&font=geist&rtl=false&menuAccent=subtle&menuColor=default&radius=default&template=start'

const SHARED_KEYS = new Set(['radius'])

function declarations(vars, indent) {
  return Object.entries(vars)
    .map(([key, value]) => `${indent}--${key}: ${value};`)
    .join('\n')
}

function passthroughDeclarations(vars, indent) {
  return Object.entries(vars)
    .map(([key, value]) => `${indent}${key}: ${value};`)
    .join('\n')
}

function themeMappings(vars) {
  return Object.keys(vars)
    .filter((key) => key !== 'radius')
    .map((key) => `  --color-${key}: var(--${key});`)
    .join('\n')
}

const response = await fetch(PRESET_URL)
if (!response.ok) {
  throw new Error(`preset fetch failed: ${response.status}`)
}
const preset = await response.json()

for (const key of Object.keys(preset.cssVars.light)) {
  if (SHARED_KEYS.has(key) && !(key in preset.cssVars.dark)) {
    preset.cssVars.dark[key] = preset.cssVars.light[key]
  }
}

const fontFamily = "'Geist Variable', sans-serif"

const css = `/* Generated by scripts/apply-shadcn-theme.mjs from ${preset.name}. Do not edit. */
:root {
${declarations(preset.cssVars.light, '  ')}
}

.dark {
${declarations(preset.cssVars.dark, '  ')}
}

@theme inline {
${themeMappings(preset.cssVars.light)}
${passthroughDeclarations(preset.cssVars.theme ?? {}, '  ')}
  --font-sans: ${fontFamily};
  --radius-sm: calc(var(--radius) - 4px);
  --radius-md: calc(var(--radius) - 2px);
  --radius-lg: var(--radius);
  --radius-xl: calc(var(--radius) + 4px);
}
`

writeFileSync(new URL('../src/theme.css', import.meta.url), css)
console.log(`wrote src/theme.css (${preset.name})`)
